// ===============================
// QUIZ VARIABLES
// ===============================

let questions = [];
let currentQuestion = 0;
let score = 0;


// ===============================
// LOAD SELECTED QUIZ
// ===============================

function loadQuiz() {

    const category =
        localStorage.getItem("quizCategory");

    const difficulty =
        localStorage.getItem("quizDifficulty");


    if (!category || !difficulty) {

        window.location.href = "quiz.html";
        return;

    }


   // Get questions according to difficulty
    questions = questionBank[difficulty];

    // Randomly select 5 questions from the 10 available
    questions = [...questions]
        .sort(() => Math.random() - 0.5)
        .slice(0, 5);

    loadQuestion();
}

// ===============================
// LOAD QUESTION
// ===============================

function loadQuestion() {

    const questionData =
        questions[currentQuestion];


    document.getElementById("question").textContent =
        questionData.question;


    const optionsContainer =
        document.getElementById("options");

    optionsContainer.innerHTML = "";


    questionData.options.forEach(
        (option, index) => {

            const button =
                document.createElement("button");

            button.className =
                "answer-option";

            button.textContent =
                option;


            button.onclick = function () {

                checkAnswer(index);

            };


            optionsContainer.appendChild(button);

        }
    );


    document.getElementById("question-number")
        .textContent =
        "Question " +
        (currentQuestion + 1) +
        " of " +
        questions.length;


    document.getElementById("score")
        .textContent =
        "Score: " + score;


    // Progress bar
    const progress =
        ((currentQuestion + 1) /
        questions.length) * 100;

    document.getElementById("progress-bar")
        .style.width =
        progress + "%";


    document.getElementById("next-button")
        .style.display =
        "none";


    document.getElementById("explanation")
        .innerHTML = "";
}


// ===============================
// CHECK ANSWER
// ===============================

function checkAnswer(selectedAnswer) {

    const correctAnswer =
        questions[currentQuestion].answer;


    const options =
        document.querySelectorAll(".answer-option");


    options.forEach(button => {

        button.disabled = true;

    });


    if (selectedAnswer === correctAnswer) {

        options[selectedAnswer]
            .classList.add("correct");

        score++;

    } else {

        options[selectedAnswer]
            .classList.add("wrong");

        options[correctAnswer]
            .classList.add("correct");

    }


    document.getElementById("score")
        .textContent =
        "Score: " + score;


    // Show explanation
    document.getElementById("explanation")
        .innerHTML =
        `<div class="explanation">
            <strong>Explanation:</strong>
            ${questions[currentQuestion].explanation}
        </div>`;


    document.getElementById("next-button")
        .style.display =
        "block";
}


// ===============================
// NEXT QUESTION
// ===============================

function nextQuestion() {

    currentQuestion++;


    if (currentQuestion < questions.length) {

        loadQuestion();

    } else {

        showResult();

    }

}


// ===============================
// SHOW RESULT
// ===============================

function showResult() {

    document.querySelector(".questions-container")
        .style.display = "none";


    document.getElementById("result-area")
        .style.display = "block";


    const total =
        questions.length;


    const wrong =
        total - score;


    const percentage =
        Math.round((score / total) * 100);


    document.getElementById("final-score")
        .textContent =
        score;


    document.querySelector(".result-score small")
        .textContent =
        "/ " + total;


    document.getElementById("correct-count")
        .textContent =
        score;


    document.getElementById("wrong-count")
        .textContent =
        wrong;


    document.getElementById("percentage")
        .textContent =
        percentage + "%";


    let message = "";


    if (percentage >= 80) {

        message =
            "Excellent! 🏆 You have strong cybersecurity knowledge.";

    } else if (percentage >= 50) {

        message =
            "Good job! 👍 Keep improving your cybersecurity knowledge.";

    } else {

        message =
            "Keep learning! 📚 Review the Cyber-Hub safety sections and try again.";

    }


    document.getElementById("result-message")
        .textContent =
        message;

}


// ===============================
// RESTART QUIZ
// ===============================

function restartQuiz() {

    currentQuestion = 0;
    score = 0;


    document.getElementById("result-area")
        .style.display = "none";


    document.querySelector(".questions-container")
        .style.display = "block";


    loadQuestion();

}


// ===============================
// START
// ===============================

loadQuiz();